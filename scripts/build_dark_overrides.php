<?php

/*
 | Generates resources/css/app-dark.generated.css: dark-mode overrides for the customer area (scoped to
 | [data-theme="dark"] .dj-app) from every rule in the client stylesheets that hard-codes a light colour.
 | Re-run after changing those stylesheets:  php scripts/build_dark_overrides.php
 */
$root = dirname(__DIR__);
$sources = ['resources/css/app.css', 'resources/css/phase1.css', 'resources/css/phase2.css', 'resources/css/refine.css', 'resources/css/site.css'];

$text = ['#17243b', '#0b1736', '#3b4257', '#0f172a', '#1e293b', '#111827', '#1d2032', '#13254f', '#334155', '#1f2937', '#0f1d3a', '#3b4a63', '#2b2f3a', '#202434'];
$muted = ['#64748b', '#6b6d7c', '#52627a', '#475569', '#6b7280', '#5b6478'];
$card = ['#fff', '#ffffff', 'white'];
$card2 = ['#f6f8fc', '#f7f9fc', '#f8fbff', '#f1f5fb', '#f8fafc', '#f4f6fa', '#f3f7ff', '#f9fafb', '#f5f7fb', '#fafbfd', '#f1f5f9', '#f6f7fb', '#fbfcfe', '#f2f5fa', '#eef3fb', '#f0f4fa', '#f5f8fd', '#fbfbfd', '#f8f9fc', '#f3f4f6'];
$line = ['#eef1f6', '#e5e9f0', '#e2e8f0', '#e3e9f1', '#d9dce6', '#e2e0ea', '#cfd8e4', '#e5e7eb', '#dde3ec', '#e6eaf2', '#eceff5', '#d7deea', '#e8ecf3', '#dfe5ee', '#edf0f5'];

$map = function (string $prop, string $value) use ($text, $muted, $card, $card2, $line): ?string {
    $v = strtolower(trim(str_replace('!important', '', $value)));
    $imp = str_contains($value, '!important') ? ' !important' : '';
    if ($prop === 'color') {
        if (in_array($v, $text, true)) {
            return "color:var(--c-text){$imp}";
        }
        if (in_array($v, $muted, true)) {
            return "color:var(--c-muted){$imp}";
        }

        return null;
    }
    if ($prop === 'background' || $prop === 'background-color') {
        if (in_array($v, $card, true)) {
            return "background:var(--c-card){$imp}";
        }
        if (in_array($v, $card2, true)) {
            return "background:var(--c-card-2){$imp}";
        }

        return null;
    }
    if (in_array($prop, ['border-color', 'border-top-color', 'border-bottom-color'], true) && in_array($v, $line, true)) {
        return "{$prop}:var(--c-line){$imp}";
    }
    if (in_array($prop, ['border', 'border-top', 'border-bottom', 'border-left', 'border-right'], true)) {
        foreach ($line as $c) {
            if (str_ends_with($v, ' '.$c)) {
                return $prop.'-color:var(--c-line)'.$imp;
            }
        }
    }

    return null;
};

$out = ['/* GENERATED by scripts/build_dark_overrides.php — do not edit by hand. Dark mode for fixed light colours in the client area. */'];
$count = 0;
foreach ($sources as $src) {
    $css = file_get_contents("$root/$src");
    $css = preg_replace('#/\*.*?\*/#s', '', $css);
    // Every innermost rule (also those inside @media); the selector is re-scoped to the dark client area.
    preg_match_all('/([^{}@;]+)\{([^{}]*)\}/', $css, $rules, PREG_SET_ORDER);
    foreach ($rules as [, $selectors, $body]) {
        $selectors = trim($selectors);
        if ($selectors === '' || str_contains($selectors, '%') || preg_match('/^(from|to)$/', $selectors) || str_contains($selectors, 'admin') || str_contains($selectors, ':root')) {
            continue;
        }
        $decls = [];
        foreach (explode(';', $body) as $decl) {
            if (! str_contains($decl, ':')) {
                continue;
            }
            [$p, $v] = array_map('trim', explode(':', $decl, 2));
            if ($m = $map(strtolower($p), $v)) {
                $decls[] = $m;
            }
        }
        if ($decls === []) {
            continue;
        }
        $scoped = [];
        foreach (explode(',', $selectors) as $sel) {
            $sel = trim($sel);
            if ($sel === '' || preg_match('/^(html|body|\*)\b/', $sel) || str_contains($sel, '.dj-header') || str_contains($sel, '.dj-footer') || str_contains($sel, '.dj-mega')) {
                continue;
            }
            $sel = preg_replace('/^\.dj-body\s+/', '', $sel);
            $sel = preg_replace('/^\.dj-body(?=[.:\[])/', '', $sel);
            $scoped[] = '[data-theme="dark"] .dj-app '.$sel;
        }
        if ($scoped === []) {
            continue;
        }
        $out[] = implode(',', array_unique($scoped)).'{'.implode(';', array_unique($decls)).'}';
        $count++;
    }
}

file_put_contents("$root/resources/css/app-dark.generated.css", implode("\n", $out)."\n");
echo "Wrote {$count} dark-mode override rules.\n";
